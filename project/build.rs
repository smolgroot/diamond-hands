// Turns studio/ and the assets it names into the data the game includes.
//
// Besides the studio's own conversion, it reads the font sheet (`assets/sprites/font.png`,
// one 8x8 cell per character, white glyph bits with a dark shadow) and writes the bit
// table the dialogue and menus stamp their text from, so the typeface lives in one
// editable picture and not in code.
use std::{env, fs, path::PathBuf};

/// The characters of the font sheet's cells, in order.
const FONT: &str = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ!:/-+.<>,'?";

fn main() {
    gba_studio_build::build();
    let sheet = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("assets/sprites/font.png");
    println!("cargo:rerun-if-changed={}", sheet.display());
    let mut decoder = png::Decoder::new(fs::File::open(&sheet).unwrap_or_else(|e| panic!("{}: {e}", sheet.display())));
    decoder.set_transformations(png::Transformations::normalize_to_color8());
    let mut reader = decoder.read_info().unwrap();
    let mut buf = vec![0; reader.output_buffer_size()];
    let info = reader.next_frame(&mut buf).unwrap();
    assert_eq!(info.color_type, png::ColorType::Rgba, "font.png must be RGBA");
    let width = info.width as usize;
    assert_eq!(width, FONT.len() * 8, "font.png needs one 8x8 cell per character");
    let mut out = String::from("/// Each glyph is seven rows of five bits, most significant bit on the left.\n/// Generated by build.rs from assets/sprites/font.png.\nconst DIALOG_GLYPHS: &[(u8, [u8; 7])] = &[\n");
    for (i, c) in FONT.bytes().enumerate() {
        let rows: Vec<String> = (0..7)
            .map(|y| {
                let bits = (0..5).fold(0u8, |acc, x| {
                    let px = &buf[(y * width + i * 8 + x) * 4..][..4];
                    // The glyph itself is the white pixels; the shadow beside it is dark.
                    acc << 1 | (px[3] > 127 && px[0] > 200 && px[1] > 200 && px[2] > 200) as u8
                });
                format!("0b{bits:05b}")
            })
            .collect();
        out += &format!("    (b'{}', [{}]),\n", if c == b'\'' { "\\'".to_string() } else { (c as char).to_string() }, rows.join(", "));
    }
    out += "];\n";
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("dialog_glyphs.rs"), out).unwrap();
}
