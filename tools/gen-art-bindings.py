#!/usr/bin/env python3
"""Generates project/src/art/studio.rs from the export manifest.

    python3 tools/gen-art-bindings.py <export dir>

One function per drawing of the old art code, named `<sheet>::<field>`, returning the
sprite (or the array of frames) as a `SpriteVram` loaded from the studio's generated
sheets. The frame numbers come from the manifest, so they follow the sheets.
"""
import json, re, sys
from pathlib import Path

manifest = json.loads((Path(sys.argv[1]) / "export.json").read_text())
out = ["// Generated by tools/gen-art-bindings.py from the art export manifest. Do not edit.",
       "//! The old art code's drawings, as the studio's sprite sheets hold them.",
       "#![allow(dead_code)]",
       "",
       "use agb::display::object::SpriteVram;",
       "",
       "use crate::gfx;",
       ""]
for sheet in manifest["sprites"]:
    name = sheet["name"]
    module = re.sub(r"[^a-z0-9]", "_", name)
    const = "SPRITE_" + re.sub(r"[^A-Za-z0-9]", "_", name).upper()
    out.append(f"pub mod {module} {{")
    out.append("    use super::*;")
    out.append("")
    for field, anim in sheet["animations"].items():
        frames = anim["frames"]
        if anim["single"]:
            out.append(f"    pub fn {field}() -> SpriteVram {{")
            out.append(f"        SpriteVram::from(&gfx::{const}.frames[{frames[0]}])")
        else:
            out.append(f"    pub fn {field}() -> [SpriteVram; {len(frames)}] {{")
            out.append(f"        const FRAMES: [usize; {len(frames)}] = {frames};")
            out.append(f"        FRAMES.map(|i| SpriteVram::from(&gfx::{const}.frames[i]))")
        out.append("    }")
        out.append("")
    out.append("}")
    out.append("")
Path(__file__).resolve().parent.parent.joinpath("project/src/art/studio.rs").write_text("\n".join(out))
print("wrote project/src/art/studio.rs")
